import { account, call, view, btcAddress, CONTRACT, MPC } from "./lib.mjs";
import { parseNearAmount } from "near-api-js";
const seller = account("pusaka-seller.testnet");
await call(seller, "nft_mint", {}, { deposit: BigInt(parseNearAmount("0.05")), tgas: 100 });
const supply = await view("nft_total_supply");
const id = String(supply);
const info = await view("token_info", { token_id: id });
console.log("token", id, "owner", info.token.owner_id, "pubkey", info.btc_pubkey);
const direct = await view("derived_public_key", { path: info.btc_path, predecessor: CONTRACT, domain_id: 0 }, MPC);
console.log("mpc direct", direct);
console.log("BTC address", btcAddress(info.btc_pubkey));
